                            <h1> A Glossary – Important Metal Fabrication Terms You Need to know </h1>

                            <p> Metal fabrication terms can sound like a whole new language to people who are unfamiliar
                                with industrial jargon. To simplify things, we have created a glossary of key terms to
                                help you familiarize yourself with the fabrication world. </p>


                            <h4> Anodizing </h4>
                            <p> It is an electrochemical process used to create a protective coating on the metal
                                surface by increasing the thickness of its natural oxide layer. </p>

                            <h4> Base Metal </h4>
                            <p> The original metal or material that is being cut, welded or modified during the
                                fabrication. </p>

                            <h4> Boring </h4>
                            <p> It is the process of enlarging an existing hole in a workpiece using a single-point
                                cutting tool.
                            </p>

                            <h4> Bending </h4>
                            <p> It is the process of bending, folding and pressing a sheet metal into the desired shape.
                            </p>

                            <h4> CAD </h4>
                            <p> Short form for Computer-Aided Design, it is a software application that is used to
                                create 2D and 3D models or parts before they are manufactured. </p>

                            <h4> CNC </h4>
                            <p> The short form for Computer Numerical Control, it is a manufacturing process aided by
                                computer programs to produce precise and geometrically accurate parts and components.
                            </p>

                            <h4> Deburring </h4>
                            <p> It is the process of removing the raised edges from the surface of a workpiece after the
                                cutting process.
                            </p>

                            <h4> Drilling </h4>
                            <p> It is a machining process that is used to create holes in a workpiece using a rotating
                                cutting tool called drill bit with cutting edges around its periphery.
                            </p>

                            <h4> Embossing </h4>
                            <p> It is a manufacturing process where patterned sheet metals are formed by placing them
                                between patterned dies or rollers.
                            </p>

                            <h4> Flame Cutting </h4>
                            <p> It is a method that uses oxyfuel gas flame to cut through steel and other metals.
                            </p>

                            <h4> Forging </h4>
                            <p> It is the process by which the heated metal is shaped using hammers, dies, presses and
                                rollers. It can be cold, warm and hot fabrication. </p>

                            <h4> Grinding </h4>
                            <p> It is the process of removing the rough edges and smoothening the surface.
                            </p>

                            <h4> Gas Metal Arc Welding </h4>
                            <p> Gas metal arc welding is a process where an electric arc is created between an electrode
                                and the workpiece metal to create the weld of both similar and dissimilar materials.
                            </p>

                            <h4> Heat-affected zone </h4>
                            <p> It is a portion of the metal near the weld that is heated during the process that
                                doesn’t melt.
                            </p>

                            <h4> Laser Cutting </h4>
                            <p> It is a fabrication process that uses highly focused laser beams to cut through metal
                                sheets with precision.
                            </p>

                            <h4> Milling </h4>
                            <p> It is a process where a rotating multi-point cutter removes material creating precise
                                and complex shapes.
                            </p>

                            <h4> Plasma Cutting </h4>
                            <p> It is a metal cutting process that uses high-velocity ionized gas to melt and cut a
                                ferrous metal.
                            </p>

                            <h4> Shearing </h4>
                            <p> It is a cold cutting process where sheet metal is cut along the straight line. </p>

                            <h4> Turning </h4>
                            <p> It is the process of removing material from the rotating metal workpiece using a
                                single-point cutting tool. </p>

                            <h4> Conclusion </h4>
                            <p> Learning the key terminologies of metal fabrication will make it easier to understand
                                the processes better. From cutting, shaping and forming to finishing and welding, each
                                term represents the important steps in the fabrication process. Familiarizing with these
                                terms will help people to understand the process and technology better.
                            </p>



